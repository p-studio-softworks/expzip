using System.IO;
using System.Text;

namespace Expzip.Splitting;

/// <summary>
/// 結合用のバッチファイル (#343)。
/// </summary>
/// <remarks>
/// <para>
/// 結合用のプログラム (exe) は署名していないので、スマート アプリ コントロールが「オン」の PC では起動を止められることがある。
/// その逃げ道として、希望すれば <c>&lt;元の名前&gt;.cmd</c> も作る。デフォルトでは作らない。
/// </para>
/// <para>
/// <b>ファイル名を命令の部分に埋め込まない。</b> 名前に <c>&amp; % ^ !</c> があると、受け取った人の PC で命令として読まれる。
/// 分割ファイルの名前はバッチファイル自身の名前 (<c>%~dpn0</c>) から組み立て、常に二重引用符の中で使う。
/// Windows のファイル名には <c>"</c> を使えないので、名前で引用符を閉じることはできない。
/// 埋め込むのは、Expzip が決める数字と 16 進と英数字の作業用の名前だけ。
/// </para>
/// <para>
/// <b>実行される部分は ASCII だけにする。</b> BOM の無い UTF-8 を cmd は OEM コードページで読むので、
/// 日本語のバイト列の途中が <c>&amp;</c> や <c>|</c> として読まれるおそれがある。日本語は、最後の <c>exit /b</c> より後ろの、
/// 実行されない欄 (手で結合する手順) にだけ置く。そこより前には括弧のブロックもサブルーチンも置かず、
/// ラベルもすべて前に置く。後ろの欄に実行が届かないようにするため。
/// </para>
/// <para>
/// 既にあるファイルは置き換えない (#320)。結合は作業用の名前 (<c>expzip-&lt;16 進&gt;.joining.tmp</c>) に書き、
/// 大きさと SHA-256 を確かめてから <c>ren</c> で本来の名前にする。<c>ren</c> は同じ名前のファイルがあると失敗するので、
/// 確かめてから名前を変えるまでの間に置かれたファイルも置き換えない。作業用の名前が既にあるときは結合しない。
/// 確かめてから書き始めるまでの一瞬の隙は、バッチファイルでは塞げない。名前に乱数を入れて、ぶつかりにくくしてある。
/// </para>
/// <para>
/// MotW: 分割ファイルかバッチファイル自身に <c>:Zone.Identifier</c> が 1 つでもあれば、結合したものに
/// <c>ZoneId=3</c> を新しく書く。中身は写さない。<c>more</c> で写すと壊れて印が落ちることがあるため。
/// 区分 4 だったものも 3 になる。
/// </para>
/// </remarks>
internal static class JoinBatch
{
    /// <summary>
    /// この名前でバッチファイルを作れるか。
    /// </summary>
    /// <remarks>
    /// 名前に <c>%</c> があると作らない。Windows はバッチファイルを起動するときに、ファイル名の <c>%OS%</c> のような部分を
    /// 環境変数の値に置き換えるので、バッチファイルが自分自身を見つけられない。命令は走らないが、逃げ道として役に立たない。
    /// 手で打つ <c>copy /b</c> も、コマンド プロンプトが同じ置き換えをする。
    /// </remarks>
    public static bool CanMake(string name) => !name.Contains('%');

    /// <summary>作業用の名前の終わり。</summary>
    public const string WorkSuffix = ".joining.tmp";

    /// <summary>作業用の名前を決める。英数字だけにする。</summary>
    public static string NewWorkName()
        => $"expzip-{Guid.NewGuid():N}"[..15] + WorkSuffix;

    /// <summary>バッチファイルの中身を書き出す。</summary>
    /// <param name="output">書き出し先。</param>
    /// <param name="name">元のファイルの名前。手で結合する手順の欄にだけ入れる。</param>
    /// <param name="parts">分割ファイルの数。</param>
    /// <param name="size">元のファイルの大きさ。</param>
    /// <param name="sha256">元のファイルの SHA-256。</param>
    /// <param name="workName">作業用の名前。英数字と <c>-</c> <c>.</c> だけ。</param>
    public static void Write(Stream output, string name, int parts, long size, byte[] sha256, string workName)
    {
        if (workName.Any(static c => !(char.IsAsciiLetterOrDigit(c) || c is '-' or '.')))
        {
            throw new ArgumentException("作業用の名前は英数字だけにする", nameof(workName));
        }

        var hash = Convert.ToHexStringLower(sha256);
        var spaced = string.Join(' ', Enumerable.Range(0, sha256.Length).Select(i => hash.Substring(i * 2, 2)));

        var text = new StringBuilder();
        void Line(string line = "") => text.Append(line).Append("\r\n");

        // ---- 実行される部分。ASCII だけ。括弧のブロックとサブルーチンを使わない
        Line("@echo off");
        Line("setlocal EnableExtensions DisableDelayedExpansion");
        Line("rem Made by Expzip to join split files. Do not edit this file.");

        // 外のプログラムは System32 のフルパスで呼ぶ。今いるフォルダー (分割ファイルの隣) に置かれた
        // findstr.exe や certutil.cmd を代わりに実行しないため。念のため、今いるフォルダーを探さない設定もする
        Line("set \"NoDefaultCurrentDirectoryInExePath=1\"");
        Line("set \"sys=%SystemRoot%\\System32\"");
        Line("set \"self=%~f0\"");
        Line($"set \"parts={parts}\"");
        Line($"set \"size={size}\"");
        Line($"set \"hash={hash}\"");
        Line($"set \"spaced={spaced}\"");
        Line($"set \"work={workName}\"");
        Line("set \"base=%~dpn0\"");
        Line("set \"rc=1\"");
        Line("set \"quiet=\"");
        Line("if /i \"%~1\"==\"-q\" set \"quiet=1\"");
        Line("set \"pushed=\"");
        Line("pushd \"%~dp0\" || goto nowrite");
        Line("set \"pushed=1\"");
        Line("set \"zone=\"");
        // 括弧で囲まないと、ストリームが無いときの「見つかりません」を 2>nul で消せない。括弧はこの行の中で閉じる
        Line("(\"%sys%\\more.com\" < \"%self%:Zone.Identifier\") >nul 2>nul && set \"zone=1\"");

        // 分割ファイルが全部あるか。番号は 3 桁、1000 個を超えたらそのまま (FileSplitter.PartPath と同じ)
        Line("set /a n=1");
        Line(":check");
        Line("set \"num=00%n%\"");
        Line("set \"num=%num:~-3%\"");
        Line("if %n% GEQ 1000 set \"num=%n%\"");
        Line("if not exist \"%base%.%num%\" goto missing");
        Line("(\"%sys%\\more.com\" < \"%base%.%num%:Zone.Identifier\") >nul 2>nul && set \"zone=1\"");
        Line("set /a n+=1");
        Line("if %n% LEQ %parts% goto check");

        Line("if exist \"%base%\" goto exists");
        Line("if exist \"%work%\" goto workexists");
        Line("if exist \"%work%.sha\" goto shaexists");

        // 1 個ずつ足す。まとめて 1 行にすると、分割ファイルが多いときに行の長さの上限 (8191 文字) を超える
        Line("copy /b \"%base%.001\" \"%work%\" >nul 2>nul || goto nowrite2");
        Line("set /a n=2");
        Line(":append");
        Line("if %n% GTR %parts% goto appended");
        Line("set \"num=00%n%\"");
        Line("set \"num=%num:~-3%\"");
        Line("if %n% GEQ 1000 set \"num=%n%\"");
        Line("copy /b \"%work%\"+\"%base%.%num%\" \"%work%\" >nul 2>nul || goto nowrite2");
        Line("set /a n+=1");
        Line("goto append");
        Line(":appended");

        // 大きさは数字の並びとして比べる。set /a は 2 GB を超える数を扱えない
        Line("set \"got=\"");
        Line("for %%F in (\"%work%\") do set \"got=%%~zF\"");
        Line("if not \"%got%\"==\"%size%\" goto mismatch");

        // SHA-256 は certutil で求める。見出しは言語で変わるので、値の行だけを丸ごと比べる。
        // 古い Windows は 2 桁ずつ空白で区切って出す。certutil が使えなければ確かめられないので結合しない
        Line("\"%sys%\\certutil.exe\" -hashfile \"%work%\" SHA256 >\"%work%.sha\" 2>nul || goto noverify");
        Line("\"%sys%\\findstr.exe\" /i /x /c:\"%hash%\" /c:\"%spaced%\" \"%work%.sha\" >nul || goto mismatch");
        Line("del \"%work%.sha\" >nul 2>nul");

        // 書けなくても止めない。FAT32 の USB メモリーは MotW を持てない。結合用のプログラムも同じ扱い
        Line("if defined zone >\"%work%:Zone.Identifier\" echo [ZoneTransfer]");
        Line("if defined zone >>\"%work%:Zone.Identifier\" echo ZoneId=3");

        // ren は同じ名前のファイルがあると失敗し、置き換えない
        Line("if exist \"%base%\" goto exists2");
        Line("ren \"%work%\" \"%~n0\" >nul 2>nul || goto renamefailed");
        Line("echo Done. The file was joined and verified.");
        Line("set \"rc=0\"");
        Line("goto end");

        Line(":missing");
        Line("echo Error: Part %n% of %parts% (.%num%) was not found. Nothing was joined.");
        Line("goto end");
        Line(":exists");
        Line("echo Error: A file with the original name already exists. Nothing was changed.");
        Line("goto end");
        Line(":workexists");
        Line("echo Error: The work file (%work%) already exists. Delete it and try again.");
        Line("goto end");
        Line(":shaexists");
        Line("echo Error: The work file (%work%.sha) already exists. Delete it and try again.");
        Line("goto end");
        Line(":nowrite");
        Line("echo Error: Could not write the joined file. Check free space and permissions.");
        Line("goto end");

        // ここから下は作業用のファイルを書き始めたあと。自分で作ったものだけを消す
        Line(":nowrite2");
        Line("echo Error: Could not write the joined file. Check free space and permissions.");
        Line("goto cleanup");
        Line(":mismatch");
        Line("echo Error: The joined file does not match the original. A part may be damaged. Nothing was joined.");
        Line("goto cleanup");
        Line(":noverify");
        Line("echo Error: Could not verify the joined file. Nothing was joined.");
        Line("goto cleanup");
        Line(":renamefailed");
        Line("if not exist \"%base%\" goto nowrite2");
        Line(":exists2");
        Line("echo Error: A file with the original name already exists. Nothing was changed.");
        Line(":cleanup");
        Line("del \"%work%.sha\" >nul 2>nul");
        Line("del \"%work%\" >nul 2>nul");

        Line(":end");
        Line("if defined pushed popd");
        Line("if not defined quiet pause");
        Line("exit /b %rc%");

        // ---- ここから下は実行されない。人がメモ帳で開いて読む欄
        var parts1 = string.Join("+", Enumerable.Range(1, parts).Select(i => $"\"{Path.GetFileName(FileSplitter.PartPath(name, i))}\""));
        var copy = $"copy /b {parts1} \"{name}\"";
        var check = $"certutil -hashfile \"{name}\" SHA256";

        // 手で打つ行を書かないとき。名前に $ や ` があると、PowerShell に貼ったときに式として動く
        // (Windows 11 の「ターミナルで開く」は PowerShell を開く)。行がコマンド プロンプトの上限 8191 文字を超えると打てない
        var manual = !name.Contains('$') && !name.Contains('`') && copy.Length < 8000;

        Line();
        Line("================================================================");
        Line("[日本語]");
        Line("このファイルは、Expzip で分割したファイルを結合するためのバッチファイルです。");
        Line("すべての分割ファイル (.001、.002 …) と同じフォルダーに置いて、ダブルクリックしてください。");
        Line("結合したあと、大きさと SHA-256 で中身を確かめます。");
        Line();

        if (manual)
        {
            Line("Windows に止められて実行できないときは、手で結合できます。");
            Line("1. 分割ファイルがあるフォルダーをエクスプローラーで開き、アドレス バーに cmd と入力して Enter キーを押します。コマンド プロンプトが開きます。");
            Line("2. 元のファイルと同じ名前のファイルが無いことを確かめてから、次の 1 行をコマンド プロンプトに入力して Enter キーを押します。");
            Line();
            Line(copy);
            Line();
            Line("3. 中身を確かめるときは、次の 1 行を入力し、表示された値が下の SHA-256 と同じかを見ます。");
            Line();
            Line(check);
            Line();
        }
        else
        {
            Line("Windows に止められて実行できないときは、7-Zip などほかのソフトで .001 を開いて結合してください。");
            Line("結合したものが元と同じかは、下の SHA-256 と比べて確かめられます。");
            Line();
        }

        Line($"SHA-256: {hash}");
        Line();

        if (manual)
        {
            Line("7-Zip などほかのソフトでも結合できます。");
            Line();
        }

        Line("[English]");
        Line("This batch file was made by Expzip to join the pieces of a split file.");
        Line("Put it in the same folder as all the pieces (.001, .002, ...) and double-click it.");
        Line("After joining, it checks the size and the SHA-256 of the result.");
        Line();

        if (manual)
        {
            Line("If Windows blocks it, you can join the pieces by hand.");
            Line("1. Open the folder with the pieces in File Explorer, type cmd in the address bar and press Enter. Command Prompt opens.");
            Line("2. Make sure no file with the original name is there, then type this line in Command Prompt and press Enter:");
            Line();
            Line(copy);
            Line();
            Line("3. To check the result, type this line and see that the value matches the SHA-256 below:");
            Line();
            Line(check);
            Line();
        }
        else
        {
            Line("If Windows blocks it, open the .001 piece with another tool such as 7-Zip and join the pieces there.");
            Line("You can check that the result matches the original by comparing it with the SHA-256 below.");
            Line();
        }

        Line($"SHA-256: {hash}");

        if (manual)
        {
            Line();
            Line("Other tools such as 7-Zip can join them too.");
        }

        // BOM は付けない。付けると 1 行目の @echo off が読めなくなる。実行される部分は ASCII なので、どの読み方でも同じ
        output.Write(new UTF8Encoding(false).GetBytes(text.ToString()));
    }
}
